package Lab_Switch;

public class LabE {
    public static void main(String[] args) {
        // 1. Print numbers 1 to 5 using for
        for (int i = 1; i <= 5; i++) {
            System.out.println(i);
        }

        // 2. Print numbers 5 down to 1 using while
        int count = 5;
        while (count >= 1) {
            System.out.println(count);
            count--;
        }
    }
}