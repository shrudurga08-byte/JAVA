package Lab_Switch;

public class LabC {
    public static void main(String[] args) {
        int choice = 2;

        if (choice == 1) {
            System.out.println("Add");
        } else if (choice == 2) {
            System.out.println("View");
        } else if (choice == 3) {
            System.out.println("Exit");
        } else {
            System.out.println("Invalid");
        }
    }
}
